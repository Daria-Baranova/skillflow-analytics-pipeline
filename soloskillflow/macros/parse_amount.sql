{# Текст суми → число.
   '$9.99' → 9.99 · '416,25 UAH' → 416.25 · '3 332,92 UAH' → 3332.92 · '-9.25 EUR' → -9.25
   Лишаємо цифри, кому, крапку і мінус; кома вважається десятковим роздільником. #}
{% macro parse_amount(column) -%}
    replace(
        regexp_replace({{ column }}, '[^0-9,.-]', '', 'g'),
        ',', '.'
    )::NUMERIC(12, 2)
{%- endmacro %}